#include "control_parameters.h"



//------------------------------------------------------------------------------------
// @brief 生成 Lite3 机器人默认参数
//------------------------------------------------------------------------------------
void ControlParameters::GenerateLite3Parameters()
{
    body_len_x_ = 0.1745*2;                         // 机器人躯干长度 [m]
    body_len_y_ = 0.062*2;                          // 机器人躯干宽度 [m]
    hip_len_ = 0.0985;                              // 机器人髋关节长度 [m]
    thigh_len_ = 0.20;                              // 机器人股骨长度 [m]
    shank_len_ = 0.21;                              // 机器人小腿长度 [m]

    pre_height_ = 0.12;                             // 机器人预设站立高度 [m]
    stand_height_ = 0.33;                           // 机器人实际站立高度 [m]
    swing_leg_kp_ << 100., 100., 100.;              // 摆动腿关节位置环增益，按 [hip,thigh,shank] 顺序排列
    swing_leg_kd_ << 2.5, 2.5, 2.5;                 // 摆动腿关节速度环增益，按 [hip,thigh,shank] 顺序排列

    fl_joint_lower_ << -0.530, -3.50, 0.349;        // 左前腿关节角度下限，按 [hip,thigh,shank] 顺序排列 [rad]
    fl_joint_upper_ << 0.530, 0.320, 2.80;          // 左前腿关节角度上限，按 [hip,thigh,shank] 顺序排列 [rad]
    joint_vel_limit_ << 30, 30, 20;                 // 关节角速度限制，按 [hip,thigh,shank] 顺序排列 [rad/s]
    torque_limit_ << 40, 40, 65;                    // 关节力矩限制，按 [hip,thigh,shank] 顺序排列 [Nm]
}



